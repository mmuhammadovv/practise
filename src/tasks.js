// Сколько задач уровня нужно решить, чтобы открыть следующий
export function requiredFor(level) {
  return Math.ceil(level.tasks.length * 0.75);
}

export function findTask(taskId) {
  for (const level of LEVELS) {
    const task = level.tasks.find((t) => t.id === taskId);
    if (task) return { level, task };
  }
  return null;
}

function normalize(s) {
  return String(s).trim().toLowerCase().replace(/\s+/g, " ");
}

export function checkAnswer(task, answer) {
  if (task.type === "choice") return Number(answer) === task.answer;
  return task.answer.some((a) => normalize(a) === normalize(answer));
}

// Версия задачи для браузера: без правильного ответа, пояснение — только после решения
export function publicTask(task, solved) {
  const { answer, explain, ...rest } = task;
  return solved ? { ...rest, explain } : rest;
}

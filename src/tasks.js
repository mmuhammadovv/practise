// Лог SSH с перебором паролей для задачи 4.8
const authLog = (() => {
  const lines = [];
  const others = ["10.0.0.15", "192.168.1.20", "77.88.55.60"];
  let t = 0;
  const ts = () => {
    t += 7;
    const m = String(10 + Math.floor(t / 60)).padStart(2, "0");
    const s = String(t % 60).padStart(2, "0");
    return `Nov 10 03:${m}:${s} srv sshd[2214]:`;
  };
  lines.push(`${ts()} Accepted password for student from 192.168.1.20 port 51022 ssh2`);
  const users = ["root", "admin", "test", "oracle", "root", "ubuntu", "root", "admin", "pi", "root", "guest", "root"];
  users.forEach((u, i) => {
    lines.push(`${ts()} Failed password for ${u} from 185.220.101.45 port ${40000 + i * 13} ssh2`);
    if (i % 4 === 1) lines.push(`${ts()} Failed password for student from ${others[i % 3]} port ${50100 + i} ssh2`);
  });
  lines.push(`${ts()} Accepted publickey for deploy from 10.0.0.15 port 60110 ssh2`);
  return lines.join("\n") + "\n";
})();

